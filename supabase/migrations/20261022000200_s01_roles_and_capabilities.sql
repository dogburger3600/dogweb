-- S01/2: autorizacao server-side, bootstrap controlado e gestao de roles.

create or replace function public.current_user_role()
returns public.user_role
language sql
stable
security definer
set search_path = public, pg_temp
as $function$
  select profiles.role
  from public.profiles
  where profiles.id = auth.uid()
$function$;

create or replace function public.has_capability(p_capability text)
returns boolean
language sql
stable
security definer
set search_path = public, pg_temp
as $function$
  select case public.current_user_role()::text
    when 'owner' then p_capability = any(array[
      'view_dashboard','view_orders','advance_orders','cancel_orders',
      'view_reports','manage_expenses','manage_stock','manage_menu',
      'manage_popup','manage_settings','view_audit','manage_roles'
    ])
    when 'manager' then p_capability = any(array[
      'view_dashboard','view_orders','advance_orders','cancel_orders',
      'view_reports','manage_expenses','manage_stock','manage_menu',
      'manage_popup','manage_settings','view_audit'
    ])
    when 'attendant' then p_capability = any(array[
      'view_dashboard','view_orders','advance_orders'
    ])
    else false
  end
$function$;

-- Compatibilidade B01-B07: "manager" continua significando administrador,
-- agora incluindo owner, mas nunca attendant/customer.
create or replace function public.is_manager()
returns boolean
language sql
stable
security definer
set search_path = public, pg_temp
as $function$
  select coalesce(public.current_user_role()::text in ('owner', 'manager'), false)
$function$;

revoke all on function public.current_user_role() from public, anon, authenticated;
revoke all on function public.has_capability(text) from public, anon, authenticated;
revoke all on function public.is_manager() from public, anon, authenticated;
grant execute on function public.current_user_role() to authenticated;
grant execute on function public.has_capability(text) to authenticated;
grant execute on function public.is_manager() to anon, authenticated;

create table if not exists public.role_change_audit_log (
  id bigint generated by default as identity primary key,
  actor_id uuid not null,
  target_id uuid not null,
  previous_role public.user_role not null,
  new_role public.user_role not null,
  created_at timestamptz not null default now()
);

alter table public.role_change_audit_log enable row level security;
revoke all on table public.role_change_audit_log from public, anon, authenticated;

drop policy if exists "role audit owner read" on public.role_change_audit_log;
create policy "role audit owner read"
on public.role_change_audit_log for select to authenticated
using (public.has_capability('manage_roles'));
grant select on public.role_change_audit_log to authenticated;

create or replace function public.set_user_role(
  p_user_id uuid,
  p_role public.user_role
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $function$
declare
  actor_role public.user_role;
  previous_role public.user_role;
  owner_count bigint;
begin
  if auth.uid() is null then
    raise exception using errcode = '42501', message = 'Autenticacao obrigatoria';
  end if;

  perform pg_advisory_xact_lock(hashtextextended('dogburger:role-management', 0));
  select role into actor_role from public.profiles where id = auth.uid() for update;
  if actor_role::text is distinct from 'owner' then
    raise exception using errcode = '42501', message = 'Somente owner pode alterar perfis de acesso';
  end if;
  if p_role is null or p_role::text not in ('owner','manager','attendant','customer') then
    raise exception using errcode = '22023', message = 'Perfil de acesso invalido';
  end if;

  select role into previous_role from public.profiles where id = p_user_id for update;
  if not found then
    raise exception using errcode = 'P0002', message = 'Usuario nao encontrado';
  end if;
  if previous_role = p_role then
    return jsonb_build_object('user_id', p_user_id, 'role', p_role::text, 'changed', false);
  end if;
  if previous_role::text = 'owner' and p_role::text <> 'owner' then
    select count(*) into owner_count from public.profiles where role::text = 'owner';
    if owner_count <= 1 then
      raise exception using errcode = '55000', message = 'O ultimo owner nao pode ser removido ou rebaixado';
    end if;
  end if;

  update public.profiles set role = p_role where id = p_user_id;
  insert into public.role_change_audit_log(actor_id, target_id, previous_role, new_role)
  values (auth.uid(), p_user_id, previous_role, p_role);
  return jsonb_build_object('user_id', p_user_id, 'previous_role', previous_role::text, 'role', p_role::text, 'changed', true);
end;
$function$;

revoke all on function public.set_user_role(uuid, public.user_role) from public, anon, authenticated;
grant execute on function public.set_user_role(uuid, public.user_role) to authenticated;

-- As contas administrativas pertencem a cada instalacao e nao podem ser
-- vinculadas a UUIDs/e-mails de outro banco. Esta migration preserva os papeis
-- que ja existem em public.profiles. A promocao inicial de uma conta deve ser
-- feita conscientemente no painel SQL da instalacao, depois de conferir o UUID
-- em auth.users.

-- Impede autoelevacao mesmo quando a policy de update proprio permite a linha.
revoke update on table public.profiles from public, anon, authenticated;
revoke update (id, email, points, role, created_at)
  on public.profiles from public, anon, authenticated;
grant update (name, phone, street, address_number, address_complement, neighborhood)
  on public.profiles to authenticated;

-- Preserva integralmente handle_new_user() e o trigger historico. Este guard
-- independente garante que todo INSERT de profile nasca customer, mesmo que
-- metadata controlada pelo usuario contenha uma role.
create or replace function public.force_new_profile_customer_role()
returns trigger
language plpgsql
set search_path = public, pg_temp
as $function$
begin
  new.role := 'customer'::public.user_role;
  return new;
end;
$function$;

drop trigger if exists s01_force_customer_role_on_insert on public.profiles;
create trigger s01_force_customer_role_on_insert
before insert on public.profiles
for each row execute function public.force_new_profile_customer_role();

revoke all on function public.force_new_profile_customer_role() from public, anon, authenticated;
