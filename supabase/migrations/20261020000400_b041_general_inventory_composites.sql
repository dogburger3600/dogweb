-- B04.1: estoque geral, produtos compostos e escolhas validadas no servidor.
-- Nao cria produtos, composicoes ou estoque de ingredientes.

alter table public.products
  add column if not exists inventory_tracked boolean not null default false,
  add column if not exists sellable boolean not null default true,
  add column if not exists is_composite boolean not null default false;

-- Preserva a semantica publicada pela B04 para os lanches existentes.
update public.products
set inventory_tracked = true
where category = 'lanches' and inventory_tracked = false;

alter table public.order_items
  add column if not exists component_selections jsonb not null default '[]'::jsonb;

alter table public.order_items
  drop constraint if exists order_items_component_selections_array;
alter table public.order_items
  add constraint order_items_component_selections_array
  check (jsonb_typeof(component_selections) = 'array');

create table if not exists public.product_components (
  parent_product_id bigint not null references public.products(id) on delete cascade,
  component_product_id bigint not null references public.products(id) on delete restrict,
  quantity integer not null check (quantity > 0),
  created_at timestamptz not null default now(),
  primary key (parent_product_id, component_product_id),
  check (parent_product_id <> component_product_id)
);

create table if not exists public.product_choice_groups (
  id bigint generated by default as identity primary key,
  parent_product_id bigint not null references public.products(id) on delete cascade,
  name text not null check (char_length(btrim(name)) between 2 and 80),
  required_quantity integer not null check (required_quantity > 0),
  created_at timestamptz not null default now(),
  unique (parent_product_id, name),
  unique (id, parent_product_id)
);

create table if not exists public.product_choice_options (
  group_id bigint not null references public.product_choice_groups(id) on delete cascade,
  component_product_id bigint not null references public.products(id) on delete restrict,
  component_quantity integer not null default 1 check (component_quantity > 0),
  created_at timestamptz not null default now(),
  primary key (group_id, component_product_id)
);

create index if not exists product_components_component_idx
  on public.product_components (component_product_id);
create index if not exists product_choice_groups_parent_idx
  on public.product_choice_groups (parent_product_id);
create index if not exists product_choice_options_component_idx
  on public.product_choice_options (component_product_id);

alter table public.product_components enable row level security;
alter table public.product_choice_groups enable row level security;
alter table public.product_choice_options enable row level security;

create or replace function public.validate_product_composition_row()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $function$
declare
  parent_is_composite boolean;
  component_is_composite boolean;
  component_tracks_inventory boolean;
  resolved_parent_id bigint;
begin
  if tg_table_name = 'product_choice_groups' then
    resolved_parent_id := new.parent_product_id;
    select is_composite into parent_is_composite
    from public.products where id = resolved_parent_id;
    if coalesce(parent_is_composite, false) is not true then
      raise exception using errcode = '23514', message = 'O produto pai deve estar marcado como composto';
    end if;
    return new;
  end if;

  if tg_table_name = 'product_choice_options' then
    select parent_product_id into resolved_parent_id
    from public.product_choice_groups where id = new.group_id;
  else
    resolved_parent_id := new.parent_product_id;
  end if;

  select is_composite into parent_is_composite
  from public.products where id = resolved_parent_id;
  select is_composite, inventory_tracked into component_is_composite, component_tracks_inventory
  from public.products where id = new.component_product_id;

  if coalesce(parent_is_composite, false) is not true then
    raise exception using errcode = '23514', message = 'O produto pai deve estar marcado como composto';
  end if;
  if coalesce(component_is_composite, false) is true then
    raise exception using errcode = '23514', message = 'Componente composto ou recursivo nao e permitido';
  end if;
  if coalesce(component_tracks_inventory, false) is not true then
    raise exception using errcode = '23514', message = 'Componente deve possuir estoque controlado';
  end if;
  if resolved_parent_id = new.component_product_id then
    raise exception using errcode = '23514', message = 'Produto composto nao pode apontar para si proprio';
  end if;
  return new;
end;
$function$;

drop trigger if exists validate_product_component on public.product_components;
create trigger validate_product_component
before insert or update on public.product_components
for each row execute function public.validate_product_composition_row();

drop trigger if exists validate_product_choice_group on public.product_choice_groups;
create trigger validate_product_choice_group
before insert or update on public.product_choice_groups
for each row execute function public.validate_product_composition_row();

drop trigger if exists validate_product_choice_option on public.product_choice_options;
create trigger validate_product_choice_option
before insert or update on public.product_choice_options
for each row execute function public.validate_product_composition_row();

create or replace function public.save_product_composition(
  p_parent_product_id bigint,
  p_fixed_components jsonb,
  p_choice_groups jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $function$
declare
  fixed_item jsonb;
  group_item jsonb;
  option_item jsonb;
  created_group_id bigint;
  fixed_count integer := 0;
  group_count integer := 0;
begin
  if auth.uid() is null or not public.is_manager() then
    raise exception using errcode = '42501', message = 'Somente gestores podem configurar composicoes';
  end if;
  if jsonb_typeof(coalesce(p_fixed_components, '[]'::jsonb)) <> 'array'
     or jsonb_typeof(coalesce(p_choice_groups, '[]'::jsonb)) <> 'array' then
    raise exception using errcode = '22023', message = 'Composicao invalida';
  end if;

  -- Pedidos usam o mesmo lock em modo compartilhado. A configuracao fica
  -- estavel enquanto cada pedido calcula e bloqueia seus produtos fisicos.
  perform pg_advisory_xact_lock(hashtextextended('dogburger:product-composition', 0));

  perform 1 from public.products where id = p_parent_product_id for update;
  if not found then
    raise exception using errcode = 'P0002', message = 'Produto pai nao encontrado';
  end if;

  if exists (
    select 1 from public.product_components where component_product_id = p_parent_product_id
    union all
    select 1 from public.product_choice_options where component_product_id = p_parent_product_id
  ) then
    raise exception using errcode = '23514', message = 'Produto usado como componente nao pode se tornar composto';
  end if;

  update public.products
  set is_composite = true,
      inventory_tracked = false,
      stock = coalesce(stock, 0)
  where id = p_parent_product_id;

  delete from public.product_components where parent_product_id = p_parent_product_id;
  delete from public.product_choice_groups where parent_product_id = p_parent_product_id;

  for fixed_item in select * from jsonb_array_elements(coalesce(p_fixed_components, '[]'::jsonb)) loop
    insert into public.product_components (parent_product_id, component_product_id, quantity)
    values (
      p_parent_product_id,
      (fixed_item->>'product_id')::bigint,
      (fixed_item->>'quantity')::integer
    );
    fixed_count := fixed_count + 1;
  end loop;

  for group_item in select * from jsonb_array_elements(coalesce(p_choice_groups, '[]'::jsonb)) loop
    insert into public.product_choice_groups (parent_product_id, name, required_quantity)
    values (
      p_parent_product_id,
      btrim(group_item->>'name'),
      (group_item->>'required_quantity')::integer
    ) returning id into created_group_id;

    if jsonb_typeof(group_item->'options') <> 'array'
       or jsonb_array_length(group_item->'options') = 0 then
      raise exception using errcode = '22023', message = 'Grupo de escolha deve possuir opcoes';
    end if;

    for option_item in select * from jsonb_array_elements(group_item->'options') loop
      insert into public.product_choice_options (group_id, component_product_id, component_quantity)
      values (
        created_group_id,
        (option_item->>'product_id')::bigint,
        coalesce((option_item->>'component_quantity')::integer, 1)
      );
    end loop;
    group_count := group_count + 1;
  end loop;

  if fixed_count = 0 and group_count = 0 then
    raise exception using errcode = '22023', message = 'Produto composto deve possuir componentes ou grupos';
  end if;

  return jsonb_build_object(
    'parent_product_id', p_parent_product_id,
    'fixed_components', fixed_count,
    'choice_groups', group_count
  );
end;
$function$;

create or replace function public.set_product_inventory_settings(
  p_product_id bigint,
  p_inventory_tracked boolean,
  p_sellable boolean
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $function$
declare
  changed_product public.products%rowtype;
begin
  if auth.uid() is null or not public.is_manager() then
    raise exception using errcode = '42501', message = 'Somente gestores podem configurar produtos';
  end if;
  perform pg_advisory_xact_lock(hashtextextended('dogburger:product-composition', 0));
  if coalesce(p_inventory_tracked, false) is false and exists (
    select 1 from public.product_components
    where component_product_id = p_product_id
    union all
    select 1 from public.product_choice_options
    where component_product_id = p_product_id
  ) then
    raise exception using errcode = '23514', message = 'Produto referenciado como componente deve manter o estoque controlado';
  end if;
  update public.products
  set inventory_tracked = case when is_composite then false else coalesce(p_inventory_tracked, false) end,
      sellable = coalesce(p_sellable, true),
      stock = coalesce(stock, 0)
  where id = p_product_id
  returning * into changed_product;
  if not found then
    raise exception using errcode = 'P0002', message = 'Produto nao encontrado';
  end if;
  return jsonb_build_object(
    'product_id', changed_product.id,
    'inventory_tracked', changed_product.inventory_tracked,
    'sellable', changed_product.sellable,
    'is_composite', changed_product.is_composite
  );
end;
$function$;

create or replace function public.restock_product(
  p_product_id bigint,
  p_quantity integer,
  p_operation_id uuid,
  p_note text default null
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $function$
declare
  selected_product public.products%rowtype;
  existing_movement public.product_stock_movements%rowtype;
  normalized_note text := nullif(btrim(p_note), '');
  new_stock integer;
begin
  if auth.uid() is null or not public.is_manager() then
    raise exception using errcode = '42501', message = 'Somente gestores podem repor estoque';
  end if;
  if p_operation_id is null or p_quantity is null or p_quantity not between 1 and 999 then
    raise exception using errcode = '22023', message = 'Operacao e quantidade validas sao obrigatorias';
  end if;
  if normalized_note is not null and char_length(normalized_note) > 500 then
    raise exception using errcode = '22023', message = 'A observacao deve ter no maximo 500 caracteres';
  end if;

  perform pg_advisory_xact_lock(hashtextextended(p_operation_id::text, 0));
  select * into existing_movement
  from public.product_stock_movements where operation_id = p_operation_id;
  if found then
    if existing_movement.product_id = p_product_id
       and existing_movement.quantity_delta = p_quantity
       and existing_movement.reason = 'manual_restock'
       and existing_movement.note is not distinct from normalized_note then
      return jsonb_build_object('product_id', p_product_id, 'stock', existing_movement.resulting_stock, 'changed', false);
    end if;
    raise exception using errcode = '22023', message = 'Identificador de operacao reutilizado com outros dados';
  end if;

  select * into selected_product from public.products where id = p_product_id for update;
  if not found or selected_product.is_composite or not selected_product.inventory_tracked then
    raise exception using errcode = '22023', message = 'Produto nao possui estoque proprio controlavel';
  end if;
  if coalesce(selected_product.stock, 0) + p_quantity > 9999 then
    raise exception using errcode = '22023', message = 'O estoque total nao pode ultrapassar 9999';
  end if;

  update public.products set stock = coalesce(stock, 0) + p_quantity
  where id = p_product_id returning stock into new_stock;
  insert into public.product_stock_movements (
    product_id, quantity_delta, resulting_stock, reason, note, created_by, operation_id
  ) values (
    p_product_id, p_quantity, new_stock, 'manual_restock', normalized_note, auth.uid(), p_operation_id
  );
  return jsonb_build_object('product_id', p_product_id, 'stock', new_stock, 'changed', true);
end;
$function$;

