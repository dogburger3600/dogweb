create or replace function public.place_order(
  p_customer_name text,
  p_note text,
  p_items jsonb,
  p_payment_method text,
  p_change_for numeric default null::numeric
)
returns bigint
language plpgsql
security definer
set search_path = public, pg_temp
as $function$
declare
  new_order_id bigint;
  item jsonb;
  selection jsonb;
  selected_product public.products%rowtype;
  requested_qty integer;
  order_address jsonb;
  order_total numeric(10,2) := 0;
  normalized_change numeric(10,2) := null;
  requirements jsonb := '{}'::jsonb;
  normalized_selections jsonb;
  component_row record;
  group_row record;
  option_row record;
  requirement_row record;
  selected_for_group integer;
  selected_qty integer;
  requirement_qty integer;
begin
  if auth.uid() is null then
    raise exception 'É necessário entrar na conta para fazer um pedido';
  end if;
  if length(trim(p_customer_name)) < 2
     or coalesce(jsonb_typeof(p_items), 'null') <> 'array'
     or jsonb_array_length(p_items) = 0 then
    raise exception 'Pedido inválido';
  end if;
  if p_payment_method not in ('pix', 'credito', 'debito', 'dinheiro') then
    raise exception 'Forma de pagamento inválida';
  end if;
  if p_payment_method = 'dinheiro' then normalized_change := p_change_for; end if;

  -- Pedidos compartilham este lock entre si; somente alteracoes de composicao
  -- usam o modo exclusivo. Assim a topologia permanece estavel sem serializar
  -- pedidos que usam conjuntos distintos de produtos.
  perform pg_advisory_xact_lock_shared(hashtextextended('dogburger:product-composition', 0));

  select jsonb_build_object(
    'street', street, 'number', address_number,
    'complement', address_complement, 'neighborhood', neighborhood
  ) into order_address from public.profiles where id = auth.uid();
  if order_address is null then raise exception 'Perfil do cliente não encontrado'; end if;

  -- Primeiro calcula e consolida toda a necessidade fisica sem bloquear linhas.
  -- A composicao permanece estavel pelo advisory lock compartilhado acima.
  for item in select * from jsonb_array_elements(p_items) loop
    begin
      requested_qty := (item->>'quantity')::integer;
    exception when others then
      raise exception 'Produto indisponível';
    end;
    select * into selected_product from public.products
    where id = (item->>'product_id')::bigint and active and sellable;
    if not found or requested_qty <= 0 then raise exception 'Produto indisponível'; end if;

    if selected_product.is_composite then
      if jsonb_typeof(coalesce(item->'component_selections', '[]'::jsonb)) <> 'array' then
        raise exception 'Escolhas de componentes inválidas';
      end if;
      for selection in select * from jsonb_array_elements(coalesce(item->'component_selections', '[]'::jsonb)) loop
        if jsonb_typeof(selection) <> 'object'
           or not (selection ?& array['group_id', 'product_id', 'quantity'])
           or coalesce(selection->>'group_id', '') !~ '^[1-9][0-9]*$'
           or coalesce(selection->>'product_id', '') !~ '^[1-9][0-9]*$'
           or coalesce(selection->>'quantity', '') !~ '^[1-9][0-9]*$' then
          raise exception 'Escolha de componente inválida';
        end if;
      end loop;
      normalized_selections := '[]'::jsonb;
      for component_row in
        select component_product_id, quantity
        from public.product_components
        where parent_product_id = selected_product.id
      loop
        requirement_qty := component_row.quantity * requested_qty;
        requirements := jsonb_set(
          requirements,
          array[component_row.component_product_id::text],
          to_jsonb(coalesce((requirements->>component_row.component_product_id::text)::integer, 0) + requirement_qty),
          true
        );
      end loop;

      for group_row in
        select id, name, required_quantity
        from public.product_choice_groups
        where parent_product_id = selected_product.id
      loop
        selected_for_group := 0;
        for selection in
          select jsonb_build_object(
            'group_id', parsed.group_id,
            'product_id', parsed.product_id,
            'quantity', sum(parsed.quantity)
          ) value
          from (
            select
              (value->>'group_id')::bigint group_id,
              (value->>'product_id')::bigint product_id,
              (value->>'quantity')::integer quantity
            from jsonb_array_elements(coalesce(item->'component_selections', '[]'::jsonb)) value
          ) parsed
          where parsed.group_id = group_row.id
          group by parsed.group_id, parsed.product_id
          order by parsed.product_id
        loop
          begin
            selected_qty := (selection->>'quantity')::integer;
          exception when others then
            raise exception 'Quantidade de escolha inválida';
          end;
          if selected_qty <= 0 then raise exception 'Quantidade de escolha inválida'; end if;

          select options.component_product_id, options.component_quantity, products.name
          into option_row
          from public.product_choice_options options
          join public.products products on products.id = options.component_product_id
          where options.group_id = group_row.id
            and options.component_product_id = (selection->>'product_id')::bigint
            and products.active and products.inventory_tracked and not products.is_composite;
          if not found then raise exception 'Escolha não permitida para o produto'; end if;

          selected_for_group := selected_for_group + selected_qty;
          requirement_qty := selected_qty * option_row.component_quantity;
          requirements := jsonb_set(
            requirements,
            array[option_row.component_product_id::text],
            to_jsonb(coalesce((requirements->>option_row.component_product_id::text)::integer, 0) + requirement_qty),
            true
          );
          normalized_selections := normalized_selections || jsonb_build_array(jsonb_build_object(
            'group_id', group_row.id,
            'group_name', group_row.name,
            'product_id', option_row.component_product_id,
            'product_name', option_row.name,
            'quantity', selected_qty
          ));
        end loop;
        if selected_for_group <> group_row.required_quantity * requested_qty then
          raise exception 'Escolhas obrigatórias incompletas para %', group_row.name;
        end if;
      end loop;

      -- Rejeita grupo estranho, opcao nao permitida ou selecao em produto sem grupo.
      for selection in select * from jsonb_array_elements(coalesce(item->'component_selections', '[]'::jsonb)) loop
        if not exists (
          select 1 from public.product_choice_groups groups
          join public.product_choice_options options on options.group_id = groups.id
          where groups.parent_product_id = selected_product.id
            and groups.id = (selection->>'group_id')::bigint
            and options.component_product_id = (selection->>'product_id')::bigint
        ) then
          raise exception 'Seleção manipulada ou não permitida';
        end if;
      end loop;
      item := jsonb_set(item, '{normalized_selections}', normalized_selections, true);
    elsif selected_product.inventory_tracked then
      requirements := jsonb_set(
        requirements,
        array[selected_product.id::text],
        to_jsonb(coalesce((requirements->>selected_product.id::text)::integer, 0) + requested_qty),
        true
      );
    elsif jsonb_array_length(coalesce(item->'component_selections', '[]'::jsonb)) > 0 then
      raise exception 'Produto simples não aceita escolhas de componentes';
    end if;
  end loop;

  -- Uma unica aquisicao de row locks inclui produtos vendidos e fisicos,
  -- sempre por ID. Nao ha fase anterior capaz de inverter a ordem global.
  perform products.id
  from public.products products
  where requirements ? products.id::text
     or products.id in (
       select distinct (raw_item->>'product_id')::bigint
       from jsonb_array_elements(p_items) raw_item
     )
  order by products.id
  for update of products;

  -- Revalida os produtos vendidos depois de adquirir todos os locks.
  if exists (
    select 1
    from jsonb_array_elements(p_items) raw_item
    left join public.products products on products.id = (raw_item->>'product_id')::bigint
    where products.id is null or not products.active or not products.sellable
  ) then
    raise exception 'Produto indisponível';
  end if;

  -- Valida o saldo ja protegido pelos locks deterministas.
  for requirement_row in
    select products.id, products.name, coalesce(products.stock, 0) stock,
           (requirements->>products.id::text)::integer required_quantity
    from public.products products
    where requirements ? products.id::text
    order by products.id
  loop
    if not exists (
      select 1 from public.products
      where id = requirement_row.id and active and inventory_tracked and not is_composite
    ) then
      raise exception 'Componente de estoque indisponível';
    end if;
    if requirement_row.stock < requirement_row.required_quantity then
      raise exception using errcode = '23514', message = format(
        'Estoque insuficiente para %s: disponível %s, solicitado %s',
        requirement_row.name, requirement_row.stock, requirement_row.required_quantity
      );
    end if;
  end loop;

  insert into public.orders (customer_id, customer_name, note, delivery_address, payment_method, change_for)
  values (auth.uid(), trim(p_customer_name), coalesce(trim(p_note), ''), order_address, p_payment_method, normalized_change)
  returning id into new_order_id;

  for item in select * from jsonb_array_elements(p_items) loop
    requested_qty := (item->>'quantity')::integer;
    select * into selected_product from public.products where id = (item->>'product_id')::bigint;
    order_total := order_total + selected_product.price * requested_qty;
    insert into public.order_items (
      order_id, product_id, product_name, quantity, unit_price, unit_cost,
      removed_ingredients, component_selections
    ) values (
      new_order_id, selected_product.id, selected_product.name, requested_qty,
      selected_product.price, selected_product.cost,
      left(coalesce(trim(item->>'removed_ingredients'), ''), 120),
      coalesce((
        select jsonb_agg(jsonb_build_object(
          'group_id', groups.id, 'group_name', groups.name,
          'product_id', options.component_product_id, 'product_name', products.name,
          'quantity', selections.quantity
        ) order by groups.id, options.component_product_id)
        from (
          select
            (selection->>'group_id')::bigint group_id,
            (selection->>'product_id')::bigint product_id,
            sum((selection->>'quantity')::integer)::integer quantity
          from jsonb_array_elements(coalesce(item->'component_selections', '[]'::jsonb)) selection
          group by (selection->>'group_id')::bigint, (selection->>'product_id')::bigint
        ) selections
        join public.product_choice_groups groups on groups.id = selections.group_id
        join public.product_choice_options options
          on options.group_id = groups.id and options.component_product_id = selections.product_id
        join public.products products on products.id = options.component_product_id
        where groups.parent_product_id = selected_product.id
      ), '[]'::jsonb)
    );
  end loop;

  for requirement_row in
    select products.id, (requirements->>products.id::text)::integer required_quantity
    from public.products products where requirements ? products.id::text order by products.id
  loop
    update public.products set stock = coalesce(stock, 0) - requirement_row.required_quantity
    where id = requirement_row.id returning stock into requirement_qty;
    insert into public.product_stock_movements (
      product_id, quantity_delta, resulting_stock, reason, order_id, created_by
    ) values (
      requirement_row.id, -requirement_row.required_quantity, requirement_qty,
      'order_debit', new_order_id, auth.uid()
    );
  end loop;

  if normalized_change is not null and normalized_change < order_total then
    raise exception 'O valor para troco deve ser igual ou maior que o total do pedido';
  end if;
  return new_order_id;
end;
$function$;

-- cancel_order da B04 ja restaura pelos order_debit reais, independentemente
-- da composicao atual. Apenas removemos o filtro antigo de categoria.
create or replace function public.cancel_order(p_order_id bigint, p_reason text)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $function$
declare
  current_status public.order_status;
  normalized_reason text := btrim(p_reason);
  existing_reason text;
  cancellation_time timestamptz;
  stock_item record;
  stock_was_restored boolean := false;
  resulting_stock integer;
begin
  if auth.uid() is null or not public.is_manager() then
    raise exception using errcode = '42501', message = 'Somente gestores podem cancelar pedidos';
  end if;
  if normalized_reason is null or char_length(normalized_reason) not between 3 and 500 then
    raise exception using errcode = '22023', message = 'A justificativa deve ter entre 3 e 500 caracteres';
  end if;
  select status into current_status from public.orders where id = p_order_id for update;
  if not found then raise exception using errcode = 'P0002', message = 'Pedido nao encontrado'; end if;
  select reason, created_at into existing_reason, cancellation_time
  from public.order_cancellations where order_id = p_order_id;
  if found then
    if existing_reason = normalized_reason then
      return jsonb_build_object(
        'order_id', p_order_id, 'cancelled', true, 'changed', false,
        'reason', existing_reason, 'cancelled_at', cancellation_time,
        'stock_restored', exists (
          select 1 from public.product_stock_movements where order_id = p_order_id and reason = 'order_restore'
        )
      );
    end if;
    raise exception using errcode = '55000', message = 'Pedido ja cancelado com outra justificativa';
  end if;
  if current_status = 'entregue' then
    raise exception using errcode = '22023', message = 'Pedido entregue nao pode ser cancelado';
  end if;
  insert into public.order_cancellations (order_id, reason, cancelled_by)
  values (p_order_id, normalized_reason, auth.uid()) returning created_at into cancellation_time;

  if current_status = 'pendente' then
    for stock_item in
      select product_id, sum(-quantity_delta)::integer restore_quantity
      from public.product_stock_movements
      where order_id = p_order_id and reason = 'order_debit' and quantity_delta < 0
      group by product_id order by product_id
    loop
      perform 1 from public.products where id = stock_item.product_id for update;
      update public.products set stock = coalesce(stock, 0) + stock_item.restore_quantity
      where id = stock_item.product_id returning stock into resulting_stock;
      insert into public.product_stock_movements (
        product_id, quantity_delta, resulting_stock, reason, order_id, created_by
      ) values (
        stock_item.product_id, stock_item.restore_quantity, resulting_stock,
        'order_restore', p_order_id, auth.uid()
      );
      stock_was_restored := true;
    end loop;
  end if;
  return jsonb_build_object(
    'order_id', p_order_id, 'cancelled', true, 'changed', true,
    'reason', normalized_reason, 'cancelled_at', cancellation_time,
    'stock_restored', stock_was_restored
  );
end;
$function$;

