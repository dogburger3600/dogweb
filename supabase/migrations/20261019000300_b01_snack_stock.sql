-- B01: auditoria futura de unidades prontas de lanches.
-- products.stock e products.min_stock ja pertencem ao contrato existente.
-- Esta migracao nao cria trigger, reset diario ou abatimento automatico.

create table if not exists public.product_stock_movements (
  id bigint generated by default as identity primary key,
  product_id bigint not null references public.products(id) on delete restrict,
  quantity_delta integer not null check (quantity_delta <> 0),
  resulting_stock integer not null check (resulting_stock >= 0),
  reason text not null check (reason in ('manual_restock', 'order_debit', 'order_restore', 'manual_adjustment')),
  order_id bigint references public.orders(id) on delete restrict,
  note text check (note is null or char_length(note) <= 500),
  created_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now()
);

comment on table public.product_stock_movements is
  'Historico futuro de unidades prontas; nao representa ingredientes e nao atualiza products automaticamente.';

create index if not exists product_stock_movements_product_created_idx
  on public.product_stock_movements (product_id, created_at desc);

create index if not exists product_stock_movements_order_idx
  on public.product_stock_movements (order_id)
  where order_id is not null;

alter table public.product_stock_movements enable row level security;

