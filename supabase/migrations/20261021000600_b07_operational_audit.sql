-- B07: auditoria operacional centralizada e append-only.
create table if not exists public.operational_audit_log (
  id bigint generated by default as identity primary key,
  actor_id uuid not null,
  action text not null check (action in (
    'order.status_changed',
    'order.cancelled',
    'inventory.restocked',
    'inventory.minimum_changed',
    'store_settings.updated'
  )),
  entity_type text not null check (entity_type in ('order', 'product', 'store_settings')),
  entity_id text not null check (char_length(btrim(entity_id)) between 1 and 120),
  context jsonb not null default '{}'::jsonb check (jsonb_typeof(context) = 'object'),
  created_at timestamptz not null default now()
);

comment on table public.operational_audit_log is
  'B07: trilha imutavel de alteracoes administrativas criticas; nao armazena credenciais ou sessoes.';

create index if not exists operational_audit_log_created_idx
  on public.operational_audit_log (created_at desc, id desc);

create index if not exists operational_audit_log_entity_idx
  on public.operational_audit_log (entity_type, entity_id, id desc);

create index if not exists operational_audit_log_actor_idx
  on public.operational_audit_log (actor_id, id desc);

alter table public.operational_audit_log enable row level security;
revoke all on table public.operational_audit_log from public, anon, authenticated;

-- Escrita interna: nao e uma API publica e valida novamente o gestor autenticado.
create or replace function public.write_operational_audit_event(
  p_action text,
  p_entity_type text,
  p_entity_id text,
  p_context jsonb
)
returns bigint
language plpgsql
security definer
set search_path = public, pg_temp
as $function$
declare
  new_event_id bigint;
begin
  if auth.uid() is null or not public.is_manager() then
    raise exception using errcode = '42501', message = 'Somente gestores podem registrar auditoria operacional';
  end if;

  if p_action is null or p_action not in (
    'order.status_changed',
    'order.cancelled',
    'inventory.restocked',
    'inventory.minimum_changed',
    'store_settings.updated'
  ) then
    raise exception using errcode = '22023', message = 'Acao de auditoria invalida';
  end if;

  if p_entity_type is null or p_entity_type not in ('order', 'product', 'store_settings')
    or nullif(btrim(p_entity_id), '') is null
    or char_length(btrim(p_entity_id)) > 120 then
    raise exception using errcode = '22023', message = 'Alvo de auditoria invalido';
  end if;

  if p_context is null or jsonb_typeof(p_context) <> 'object' then
    raise exception using errcode = '22023', message = 'Contexto de auditoria invalido';
  end if;

  insert into public.operational_audit_log (actor_id, action, entity_type, entity_id, context)
  values (auth.uid(), p_action, p_entity_type, btrim(p_entity_id), p_context)
  returning id into new_event_id;

  return new_event_id;
end;
$function$;

comment on function public.write_operational_audit_event(text, text, text, jsonb) is
  'B07 interna: grava evento allowlisted; nao deve ser executavel pelos papeis da aplicacao.';

revoke all on function public.write_operational_audit_event(text, text, text, jsonb)
  from public, anon, authenticated;

-- Consulta paginada: a tabela continua sem SELECT direto para os papeis da aplicacao.
create or replace function public.get_operational_audit(
  p_limit integer default 100,
  p_before_id bigint default null,
  p_entity_type text default null,
  p_entity_id text default null
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $function$
declare
  normalized_limit integer;
  events jsonb;
begin
  if auth.uid() is null or not public.is_manager() then
    raise exception using errcode = '42501', message = 'Somente gestores podem consultar auditoria operacional';
  end if;

  if p_limit is null or p_limit not between 1 and 200 then
    raise exception using errcode = '22023', message = 'O limite deve estar entre 1 e 200';
  end if;
  normalized_limit := p_limit;

  if p_before_id is not null and p_before_id <= 0 then
    raise exception using errcode = '22023', message = 'Cursor de auditoria invalido';
  end if;
  if p_entity_type is not null and p_entity_type not in ('order', 'product', 'store_settings') then
    raise exception using errcode = '22023', message = 'Tipo de entidade invalido';
  end if;
  if p_entity_id is not null and (nullif(btrim(p_entity_id), '') is null or char_length(btrim(p_entity_id)) > 120) then
    raise exception using errcode = '22023', message = 'Identificador de entidade invalido';
  end if;

  select coalesce(jsonb_agg(jsonb_build_object(
    'id', selected.id,
    'actor_id', selected.actor_id,
    'action', selected.action,
    'entity_type', selected.entity_type,
    'entity_id', selected.entity_id,
    'context', selected.context,
    'created_at', selected.created_at
  ) order by selected.id desc), '[]'::jsonb)
  into events
  from (
    select audit.id, audit.actor_id, audit.action, audit.entity_type, audit.entity_id, audit.context, audit.created_at
    from public.operational_audit_log audit
    where (p_before_id is null or audit.id < p_before_id)
      and (p_entity_type is null or audit.entity_type = p_entity_type)
      and (p_entity_id is null or audit.entity_id = btrim(p_entity_id))
    order by audit.id desc
    limit normalized_limit
  ) selected;

  return jsonb_build_object(
    'events', events,
    'next_before_id', case
      when jsonb_array_length(events) = normalized_limit
      then (events -> (jsonb_array_length(events) - 1) ->> 'id')::bigint
      else null
    end
  );
end;
$function$;

comment on function public.get_operational_audit(integer, bigint, text, text) is
  'B07: consulta administrativa paginada da trilha operacional, mais recente primeiro.';

revoke all on function public.get_operational_audit(integer, bigint, text, text)
  from public, anon, authenticated;
grant execute on function public.get_operational_audit(integer, bigint, text, text)
  to authenticated;

-- B02: mesmo contrato e mesmas transicoes; somente mudancas efetivas geram auditoria B07.
create or replace function public.transition_order_status(
  p_order_id bigint,
  p_to_status text
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $function$
declare
  current_status public.order_status;
  target_status public.order_status;
begin
  if auth.uid() is null or not public.is_manager() then
    raise exception using errcode = '42501', message = 'Somente gestores podem alterar o estado de pedidos';
  end if;
  if p_to_status is null or p_to_status not in ('pendente', 'preparando', 'pronto', 'entregue') then
    raise exception using errcode = '22023', message = 'Estado de destino invalido';
  end if;
  target_status := p_to_status::public.order_status;
  select orders.status into current_status from public.orders where orders.id = p_order_id for update;
  if not found then raise exception using errcode = 'P0002', message = 'Pedido nao encontrado'; end if;
  if exists (select 1 from public.order_cancellations where order_id = p_order_id) then
    raise exception using errcode = '55000', message = 'Pedido cancelado nao pode mudar de estado';
  end if;
  if current_status = target_status then
    return jsonb_build_object('order_id', p_order_id, 'status', current_status::text, 'changed', false);
  end if;
  if not (
    (current_status = 'pendente' and target_status = 'preparando')
    or (current_status = 'preparando' and target_status = 'pronto')
    or (current_status = 'pronto' and target_status = 'entregue')
  ) then
    raise exception using errcode = '22023', message = format('Transicao de %s para %s nao permitida', current_status::text, target_status::text);
  end if;
  update public.orders set status = target_status where id = p_order_id;
  insert into public.order_status_history (order_id, from_status, to_status, changed_by)
  values (p_order_id, current_status::text, target_status::text, auth.uid());
  perform public.write_operational_audit_event(
    'order.status_changed', 'order', p_order_id::text,
    jsonb_build_object('from_status', current_status::text, 'to_status', target_status::text)
  );
  return jsonb_build_object('order_id', p_order_id, 'status', target_status::text, 'changed', true);
end;
$function$;

-- B04: mesmo cancelamento idempotente e mesma restauracao condicional de estoque.
create or replace function public.cancel_order(p_order_id bigint, p_reason text)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $function$
declare
  current_status public.order_status;
  normalized_reason text := btrim(p_reason);
  existing_reason text;
  cancellation_time timestamptz;
  stock_item record;
  resulting_stock integer;
  stock_was_restored boolean := false;
begin
  if auth.uid() is null or not public.is_manager() then raise exception using errcode = '42501', message = 'Somente gestores podem cancelar pedidos'; end if;
  if normalized_reason is null or char_length(normalized_reason) not between 3 and 500 then raise exception using errcode = '22023', message = 'A justificativa deve ter entre 3 e 500 caracteres'; end if;
  select status into current_status from public.orders where id = p_order_id for update;
  if not found then raise exception using errcode = 'P0002', message = 'Pedido nao encontrado'; end if;
  select reason, created_at into existing_reason, cancellation_time from public.order_cancellations where order_id = p_order_id;
  if found then
    if existing_reason = normalized_reason then
      return jsonb_build_object('order_id', p_order_id, 'cancelled', true, 'changed', false, 'reason', existing_reason, 'cancelled_at', cancellation_time, 'stock_restored', exists (select 1 from public.product_stock_movements where order_id = p_order_id and reason = 'order_restore'));
    end if;
    raise exception using errcode = '55000', message = 'Pedido ja cancelado com outra justificativa';
  end if;
  if current_status = 'entregue' then raise exception using errcode = '22023', message = 'Pedido entregue nao pode ser cancelado'; end if;
  insert into public.order_cancellations (order_id, reason, cancelled_by)
  values (p_order_id, normalized_reason, auth.uid()) returning created_at into cancellation_time;
  if current_status = 'pendente' then
    for stock_item in
      select movements.product_id, sum(-movements.quantity_delta)::integer as restore_quantity
      from public.product_stock_movements movements
      join public.products products on products.id = movements.product_id
      where movements.order_id = p_order_id and movements.reason = 'order_debit'
        and movements.quantity_delta < 0 and products.category = 'lanches'
        and not exists (select 1 from public.product_stock_movements restored where restored.order_id = p_order_id and restored.product_id = movements.product_id and restored.reason = 'order_restore')
      group by movements.product_id order by movements.product_id
    loop
      perform 1 from public.products where id = stock_item.product_id for update;
      update public.products set stock = coalesce(stock, 0) + stock_item.restore_quantity
        where id = stock_item.product_id returning stock into resulting_stock;
      insert into public.product_stock_movements (product_id, quantity_delta, resulting_stock, reason, order_id, created_by)
      values (stock_item.product_id, stock_item.restore_quantity, resulting_stock, 'order_restore', p_order_id, auth.uid());
      stock_was_restored := true;
    end loop;
  end if;
  perform public.write_operational_audit_event(
    'order.cancelled', 'order', p_order_id::text,
    jsonb_build_object('status_at_cancellation', current_status::text, 'reason', normalized_reason, 'stock_restored', stock_was_restored)
  );
  return jsonb_build_object('order_id', p_order_id, 'cancelled', true, 'changed', true, 'reason', normalized_reason, 'cancelled_at', cancellation_time, 'stock_restored', stock_was_restored);
end;
$function$;

-- B04: mesma idempotencia por operation_id; repeticoes nao geram evento duplicado.
create or replace function public.restock_snack_product(p_product_id bigint, p_quantity integer, p_operation_id uuid, p_note text default null)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $function$
declare
  selected_product public.products%rowtype;
  existing_movement public.product_stock_movements%rowtype;
  new_stock integer;
  normalized_note text := nullif(btrim(p_note), '');
begin
  if auth.uid() is null or not public.is_manager() then raise exception using errcode = '42501', message = 'Somente gestores podem repor estoque'; end if;
  if p_operation_id is null then raise exception using errcode = '22023', message = 'Identificador da operacao e obrigatorio'; end if;
  if p_quantity is null or p_quantity not between 1 and 999 then raise exception using errcode = '22023', message = 'A quantidade deve estar entre 1 e 999'; end if;
  if normalized_note is not null and char_length(normalized_note) > 500 then raise exception using errcode = '22023', message = 'A observacao deve ter no maximo 500 caracteres'; end if;
  perform pg_advisory_xact_lock(hashtextextended(p_operation_id::text, 0));
  select * into existing_movement from public.product_stock_movements where operation_id = p_operation_id;
  if found then
    if existing_movement.product_id = p_product_id and existing_movement.quantity_delta = p_quantity and existing_movement.reason = 'manual_restock' and existing_movement.note is not distinct from normalized_note then
      return jsonb_build_object('product_id', p_product_id, 'stock', existing_movement.resulting_stock, 'changed', false);
    end if;
    raise exception using errcode = '22023', message = 'Identificador de operacao reutilizado com outros dados';
  end if;
  select * into selected_product from public.products where id = p_product_id for update;
  if not found or selected_product.category <> 'lanches' then raise exception using errcode = '22023', message = 'Produto nao e um lanche valido'; end if;
  if coalesce(selected_product.stock, 0) + p_quantity > 9999 then raise exception using errcode = '22023', message = 'O estoque total nao pode ultrapassar 9999'; end if;
  update public.products set stock = coalesce(stock, 0) + p_quantity where id = p_product_id returning stock into new_stock;
  insert into public.product_stock_movements (product_id, quantity_delta, resulting_stock, reason, note, created_by, operation_id)
  values (p_product_id, p_quantity, new_stock, 'manual_restock', normalized_note, auth.uid(), p_operation_id);
  perform public.write_operational_audit_event(
    'inventory.restocked', 'product', p_product_id::text,
    jsonb_build_object('previous_stock', coalesce(selected_product.stock, 0), 'quantity_delta', p_quantity, 'resulting_stock', new_stock, 'operation_id', p_operation_id)
  );
  return jsonb_build_object('product_id', p_product_id, 'stock', new_stock, 'changed', true);
end;
$function$;

create or replace function public.set_snack_min_stock(p_product_id bigint, p_min_stock integer)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $function$
declare
  selected_product public.products%rowtype;
  updated_stock integer;
begin
  if auth.uid() is null or not public.is_manager() then raise exception using errcode = '42501', message = 'Somente gestores podem definir estoque minimo'; end if;
  if p_min_stock is null or p_min_stock not between 0 and 999 then raise exception using errcode = '22023', message = 'O estoque minimo deve estar entre 0 e 999'; end if;
  select * into selected_product from public.products where id = p_product_id and category = 'lanches' for update;
  if not found then raise exception using errcode = '22023', message = 'Produto nao e um lanche valido'; end if;
  update public.products set min_stock = p_min_stock where id = p_product_id returning stock into updated_stock;
  if selected_product.min_stock is distinct from p_min_stock then
    perform public.write_operational_audit_event(
      'inventory.minimum_changed', 'product', p_product_id::text,
      jsonb_build_object('previous_min_stock', selected_product.min_stock, 'new_min_stock', p_min_stock, 'current_stock', updated_stock)
    );
  end if;
  return jsonb_build_object('product_id', p_product_id, 'min_stock', p_min_stock, 'stock', updated_stock);
end;
$function$;

-- B05: mesmas validacoes e retorno; auditoria registra somente nomes dos campos alterados.
create or replace function public.update_store_settings(p_settings jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $function$
declare
  previous_settings public.store_settings%rowtype;
  settings public.store_settings%rowtype;
  changed_fields text[];
begin
  if auth.uid() is null or not public.is_manager() then raise exception using errcode = '42501', message = 'Somente gestores podem atualizar configurações'; end if;
  if jsonb_typeof(p_settings) <> 'object' then raise exception using errcode = '22023', message = 'Configurações inválidas'; end if;
  if nullif(btrim(p_settings->>'whatsapp'), '') is null then raise exception using errcode = '22023', message = 'WhatsApp não pode ficar vazio'; end if;
  if nullif(btrim(p_settings->>'instagram'), '') is null then raise exception using errcode = '22023', message = 'Instagram não pode ficar vazio'; end if;
  if nullif(btrim(p_settings->>'location_name'), '') is null then raise exception using errcode = '22023', message = 'Localização não pode ficar vazia'; end if;

  select * into previous_settings from public.store_settings where id = 1 for update;
  if not found then raise exception using errcode = 'P0002', message = 'Configurações da loja não encontradas'; end if;

  update public.store_settings set
    open_time = (p_settings->>'open_time')::time, close_time = (p_settings->>'close_time')::time,
    pause_enabled = coalesce((p_settings->>'pause_enabled')::boolean, false),
    pause_start = nullif(p_settings->>'pause_start','')::time, pause_end = nullif(p_settings->>'pause_end','')::time,
    whatsapp = btrim(p_settings->>'whatsapp'), instagram = btrim(p_settings->>'instagram'), location_name = btrim(p_settings->>'location_name'),
    latitude = (p_settings->>'latitude')::numeric, longitude = (p_settings->>'longitude')::numeric,
    delivery_enabled = (p_settings->>'delivery_enabled')::boolean, pickup_enabled = (p_settings->>'pickup_enabled')::boolean,
    accepts_pix = (p_settings->>'accepts_pix')::boolean, accepts_cash = (p_settings->>'accepts_cash')::boolean, accepts_card = (p_settings->>'accepts_card')::boolean,
    delivery_eta_min = (p_settings->>'delivery_eta_min')::integer, delivery_eta_max = (p_settings->>'delivery_eta_max')::integer,
    pickup_eta_min = (p_settings->>'pickup_eta_min')::integer, pickup_eta_max = (p_settings->>'pickup_eta_max')::integer,
    delivery_fee = (p_settings->>'delivery_fee')::numeric, free_delivery_from = (p_settings->>'free_delivery_from')::numeric,
    updated_by = auth.uid(), updated_at = now()
  where id = 1 returning * into settings;

  if settings.open_time = settings.close_time or (settings.pause_enabled and (settings.pause_start is null or settings.pause_end is null or settings.pause_start = settings.pause_end))
    or not (settings.delivery_enabled or settings.pickup_enabled) or not (settings.accepts_pix or settings.accepts_cash or settings.accepts_card)
    or settings.delivery_eta_max < settings.delivery_eta_min or settings.pickup_eta_max < settings.pickup_eta_min then
    raise exception using errcode = '22023', message = 'Configurações inválidas';
  end if;

  changed_fields := array_remove(array[
    case when previous_settings.open_time is distinct from settings.open_time then 'open_time' end,
    case when previous_settings.close_time is distinct from settings.close_time then 'close_time' end,
    case when previous_settings.pause_enabled is distinct from settings.pause_enabled then 'pause_enabled' end,
    case when previous_settings.pause_start is distinct from settings.pause_start then 'pause_start' end,
    case when previous_settings.pause_end is distinct from settings.pause_end then 'pause_end' end,
    case when previous_settings.whatsapp is distinct from settings.whatsapp then 'whatsapp' end,
    case when previous_settings.instagram is distinct from settings.instagram then 'instagram' end,
    case when previous_settings.location_name is distinct from settings.location_name then 'location_name' end,
    case when previous_settings.latitude is distinct from settings.latitude then 'latitude' end,
    case when previous_settings.longitude is distinct from settings.longitude then 'longitude' end,
    case when previous_settings.delivery_enabled is distinct from settings.delivery_enabled then 'delivery_enabled' end,
    case when previous_settings.pickup_enabled is distinct from settings.pickup_enabled then 'pickup_enabled' end,
    case when previous_settings.accepts_pix is distinct from settings.accepts_pix then 'accepts_pix' end,
    case when previous_settings.accepts_cash is distinct from settings.accepts_cash then 'accepts_cash' end,
    case when previous_settings.accepts_card is distinct from settings.accepts_card then 'accepts_card' end,
    case when previous_settings.delivery_eta_min is distinct from settings.delivery_eta_min then 'delivery_eta_min' end,
    case when previous_settings.delivery_eta_max is distinct from settings.delivery_eta_max then 'delivery_eta_max' end,
    case when previous_settings.pickup_eta_min is distinct from settings.pickup_eta_min then 'pickup_eta_min' end,
    case when previous_settings.pickup_eta_max is distinct from settings.pickup_eta_max then 'pickup_eta_max' end,
    case when previous_settings.delivery_fee is distinct from settings.delivery_fee then 'delivery_fee' end,
    case when previous_settings.free_delivery_from is distinct from settings.free_delivery_from then 'free_delivery_from' end
  ]::text[], null);

  if coalesce(array_length(changed_fields, 1), 0) > 0 then
    perform public.write_operational_audit_event(
      'store_settings.updated', 'store_settings', settings.id::text,
      jsonb_build_object('changed_fields', to_jsonb(changed_fields))
    );
  end if;

  return public.get_store_settings();
end;
$function$;

