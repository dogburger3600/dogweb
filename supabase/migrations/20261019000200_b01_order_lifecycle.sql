-- B01: estruturas preparatorias para cancelamento e historico de pedidos.
-- Nao altera orders.status, nao cria trigger e nao muda a RPC place_order.

create table if not exists public.order_cancellations (
  order_id bigint primary key references public.orders(id) on delete restrict,
  reason text not null check (char_length(btrim(reason)) between 3 and 500),
  cancelled_by uuid not null references public.profiles(id) on delete restrict,
  created_at timestamptz not null default now()
);

comment on table public.order_cancellations is
  'Cancelamento explicito e separado do status legado do pedido.';

create index if not exists order_cancellations_created_at_idx
  on public.order_cancellations (created_at desc);

create table if not exists public.order_status_history (
  id bigint generated by default as identity primary key,
  order_id bigint not null references public.orders(id) on delete cascade,
  from_status text,
  to_status text not null,
  changed_by uuid references public.profiles(id) on delete set null,
  note text check (note is null or char_length(note) <= 500),
  created_at timestamptz not null default now(),
  check (from_status is null or from_status <> to_status)
);

comment on table public.order_status_history is
  'Trilha append-only preparada para transicoes de pedido; preenchimento fica para uma Task posterior.';

create index if not exists order_status_history_order_created_idx
  on public.order_status_history (order_id, created_at desc);

alter table public.order_cancellations enable row level security;
alter table public.order_status_history enable row level security;

